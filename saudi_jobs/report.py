"""Self-contained HTML report (inline CSS, inline base64 PNG charts, no scripts)."""
from __future__ import annotations

import base64
from html import escape

import pandas as pd

from saudi_jobs import analytics as an
from saudi_jobs.gap import GapResult
from saudi_jobs.skills import Taxonomy

SYNTHETIC_NOTICE = ("SYNTHETIC DEMO DATA. These postings were generated by a script with invented parameters. "
                    "Nothing in this report describes the real Saudi job market.")
GENERIC_NOTICE = ("These figures describe only the postings in the supplied file. They are not market-wide "
                  "statistics unless that file is a representative sample.")

CSS = """body{font-family:system-ui,sans-serif;max-width:980px;margin:2rem auto;padding:0 1rem;color:#1b2733}
h1{margin-bottom:.2rem}h2{margin-top:2rem;border-bottom:1px solid #d5dbe1;padding-bottom:.2rem}
.notice{background:#fff3cd;border:1px solid #e0c36a;padding:.7rem 1rem;border-radius:6px;font-weight:600}
table{border-collapse:collapse;margin:.5rem 0}td,th{border:1px solid #d5dbe1;padding:.25rem .6rem;text-align:right}
th{background:#eef2f6}td:first-child,th:first-child{text-align:left}img{max-width:100%;height:auto}
.kpi{display:inline-block;margin:.3rem 1rem .3rem 0}.kpi b{font-size:1.4rem;display:block}"""


def table_html(df: pd.DataFrame, index: bool = False) -> str:
    d = df.reset_index() if index else df
    head = "".join(f"<th>{escape(str(c))}</th>" for c in d.columns)
    body = "".join("<tr>" + "".join(f"<td>{escape(str(v))}</td>" for v in row) + "</tr>"
                   for row in d.itertuples(index=False))
    return f"<table><tr>{head}</tr>{body}</table>"


def _img(png: bytes, alt: str) -> str:
    return f'<img alt="{escape(alt)}" src="data:image/png;base64,{base64.b64encode(png).decode()}">'


def build_report(df: pd.DataFrame, tax: Taxonomy, pngs: dict[str, bytes], quality: dict | None = None,
                 gap: GapResult | None = None) -> str:
    notice = SYNTHETIC_NOTICE if an.is_synthetic(df) else GENERIC_NOTICE
    q = quality or an.data_quality(df)
    kpis = "".join(f'<div class="kpi"><b>{escape(str(v))}</b>{escape(k)}</div>' for k, v in [
        ("postings", f"{q['postings']:,}"), ("with salary", f"{q['with_salary_pct']}%"),
        ("unclassified role", f"{q['role_other_pct']}%"), ("no skill found", f"{q['no_skill_found_pct']}%")])
    parts = [
        f"<!doctype html><html lang='en'><head><meta charset='utf-8'><title>Job Market Report</title>"
        f"<meta name='viewport' content='width=device-width,initial-scale=1'><style>{CSS}</style></head><body>",
        f"<div class='notice'>{escape(notice)}</div>",
        "<h1>Job posting analysis</h1>", kpis,
        "<h2>Top skills</h2>", _img(pngs["top_skills"], "Top skills"),
        table_html(an.top_skills(df, tax, n=15)),
        "<h2>Skills by role</h2>", _img(pngs["role_heatmap"], "Skills by role heatmap"),
        "<h2>Rising and falling skills</h2>", _img(pngs["trend"], "Monthly trend"),
        "<p>Change in share between the first and last third of the months covered.</p>",
        table_html(an.trend_movers(df, n=5)),
        "<h2>Skill co-occurrence</h2>", _img(pngs["cooccurrence"], "Co-occurrence"),
        "<p>Most frequent pairs (lift above 1 means they appear together more than chance).</p>",
        table_html(an.top_pairs(df, n=10)),
        "<h2>Cities and sectors</h2>", _img(pngs["city_sector"], "Cities and sectors"),
        "<h2>Roles, salary and seniority</h2>",
        "<p>Salary: monthly SAR midpoint of advertised ranges, only for postings that state one.</p>",
        table_html(an.breakdown(df, "role")), table_html(an.seniority_split(df), index=True),
    ]
    if gap is not None:
        parts += [f"<h2>Skills gap for {escape(gap.role)}</h2>",
                  f"<p>Based on {gap.n_postings:,} postings. Coverage of the role's top-10 skills: "
                  f"{gap.coverage_top10_pct}%.</p>", table_html(gap.missing)]
    parts += ["<h2>Data quality</h2>", table_html(pd.DataFrame(list(q.items()), columns=["metric", "value"])),
              "</body></html>"]
    return "\n".join(parts)
